def get_random_puzzle(difficulty: str = "classic") -> Sample:
    """Generate a real-time unique Sudoku puzzle for the requested difficulty."""
    diff_key = difficulty.lower()
    if diff_key not in PUZZLE_SEEDS:
        diff_key = "classic"

    seeds = PUZZLE_SEEDS[diff_key]
    base = random.choice(seeds)

    # Apply random permutation of digits 1-9 to produce a completely distinct puzzle
    digits = list(range(1, 10))
    perm = list(range(1, 10))
    random.shuffle(perm)

    mapping = {0: 0}
    for orig, p in zip(digits, perm):
        mapping[orig] = p

    new_board = [[mapping[val] for val in row] for row in base]

    name_label = diff_key.capitalize()
    return Sample(
        id=f"{diff_key}-{uuid.uuid4().hex[:6]}",
        name=name_label,
        board=new_board,
    )
